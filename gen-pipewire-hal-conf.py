"""Generates pipewire-hal.conf from the FuriOS file pipewire-droid.conf.

Instead of a copy, only two things are inserted:
  1. api.droid.* -> our SPA plugin in context.spa-libs
     (device and nodes are created by WirePlumber, see wireplumber/droid.lua)
  2. an echo canceller at the end of context.modules (see ECHO_CANCEL)

That way later FuriOS changes to pipewire-droid.conf are carried along as soon
as this script is run again.
"""
import re
import sys

NODE = ""   # device and nodes come from WirePlumber (droid.lua)

# An echo canceller for calls in apps - a browser, a messenger. A mobile call
# has the modem's own (see FINDINGS.md); everything else had none, and a voice
# chat in Firefox over the speaker heard itself (2026-10-17).
#
# Nothing is routed here by this file. droid-echo-cancel.lua sends only the
# streams of an app that plays and records at the same time, and only while
# furios.echo-cancel is on. Unused, it costs nothing: both inner streams are
# passive, so droid-source stays suspended and the CPU at 0 (measured). In a
# conversation webrtc takes 10-20 % of a core.
#
# The capture is pinned to the phone microphone: following the default source
# would make it record itself the day the default lands on its own source.
# Playback follows the default sink, so a headset still gets the voice.
# Mono at 48 kHz: voice, and half the work of stereo.
ECHO_CANCEL = """\
    # Added by gen-pipewire-hal-conf.py - see droid-echo-cancel.lua.
    { name = libpipewire-module-echo-cancel
        args = {
            library.name   = aec/libspa-aec-webrtc
            audio.rate     = 48000
            audio.channels = 1
            audio.position = [ MONO ]
            capture.props = {
                node.name     = "furios-echo-cancel-capture"
                target.object = "droid-source"
                node.passive  = true
            }
            source.props = {
                node.name        = "furios-echo-cancel-source"
                node.description = "Microphone (echo cancelled)"
                priority.session = 1
                priority.driver  = 1
            }
            sink.props = {
                node.name        = "furios-echo-cancel-sink"
                node.description = "Speaker (echo cancelled)"
                priority.session = 1
                priority.driver  = 1
            }
            playback.props = {
                node.name    = "furios-echo-cancel-playback"
                node.passive = true
            }
        }
        flags = [ ifexists nofail ]
    }
"""


def main():
    src, dst = sys.argv[1], sys.argv[2]
    text = open(src).read()

    # 1) register the SPA library
    if "api.droid." in text:
        print("note: api.droid.* is already in the template", file=sys.stderr)
    else:
        m = re.search(r"^context\.spa-libs\s*=\s*\{\s*$", text, re.M)
        if not m:
            print("ERROR: context.spa-libs not found", file=sys.stderr)
            return 1
        insert = m.end() + 1
        text = (text[:insert]
                + "    api.droid.*     = droid/libspa-droid\n"
                + text[insert:])

    # 2) append the device
    m = re.search(r"^context\.objects\s*=\s*\[\s*$", text, re.M)
    if not m:
        print("ERROR: context.objects not found", file=sys.stderr)
        return 1
    insert = m.end() + 1
    text = text[:insert] + NODE + text[insert:]

    # 3) the echo canceller, at the end of context.modules
    if "libpipewire-module-echo-cancel" in text:
        print("note: an echo canceller is already in the template", file=sys.stderr)
    else:
        m = re.search(r"^context\.modules\s*=\s*\[\s*$", text, re.M)
        end = m and re.search(r"^\]\s*$", text[m.end():], re.M)
        if not end:
            print("ERROR: end of context.modules not found", file=sys.stderr)
            return 1
        insert = m.end() + end.start()
        text = text[:insert] + ECHO_CANCEL + text[insert:]

    header = ("# Generated by gen-pipewire-hal-conf.py from %s\n"
              "# Do NOT edit by hand - run the script again instead.\n" % src)
    open(dst, "w").write(header + text)
    print("%s -> %s" % (src, dst))
    return 0


if __name__ == "__main__":
    sys.exit(main())
